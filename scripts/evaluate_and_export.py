"""
evaluate_and_export.py
======================
Single source of truth for every number quoted about this project.

Run from the repository root:

    python scripts/evaluate_and_export.py

Writes two files:

    results.json          dataset facts and evaluation metrics (test split)
    docs/demo/model.json  TF-IDF vocabulary, LR weights and the VADER lexicon
                          for the in-browser demo

The script also re-scores the test split from model.json with a pure-Python
re-implementation and stops if it disagrees with scikit-learn, so the demo
computes exactly what the evaluated model computes.
"""

import hashlib
import json
import math
import platform
import re
import sys
import unicodedata
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

import nltk
import numpy as np
import sklearn
from sklearn.metrics import precision_recall_fscore_support
from sklearn.model_selection import train_test_split

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import financial_sentiment_model as fsm  # noqa: E402
from nltk.sentiment.vader import SentimentIntensityAnalyzer  # noqa: E402

ROUND = 5  # decimals stored in model.json

# Self-written sentences (not from the dataset), scored by both models.
PROBE_SENTENCES = [
    "The group faces significant headwinds in its main markets.",
    "Management successfully avoided a larger writedown.",
    "Net loss narrowed to EUR 2 million from EUR 9 million.",
    "The bank cut its full-year guidance.",
    "Revenue was flat compared with last year.",
    "Operating profit rose to EUR 14 million.",
]


def per_class(y_true, y_pred):
    p, r, f, s = precision_recall_fscore_support(
        y_true, y_pred, labels=[0, 1, 2], zero_division=0
    )
    return {
        name: {"precision": float(p[k]), "recall": float(r[k]),
               "f1": float(f[k]), "support": int(s[k])}
        for k, name in enumerate(fsm.LABEL_NAMES)
    }


def summarize(metrics, y_true, y_pred):
    return {
        "accuracy": float(metrics["accuracy"]),
        "f1_macro": float(metrics["f1_macro"]),
        "per_class": per_class(y_true, y_pred),
        "confusion_matrix": metrics["conf_matrix"].tolist(),
        "confusion_matrix_note": "rows = true label, columns = predicted; order negative, neutral, positive",
    }


# ---------------------------------------------------------------------------
# Pure-Python scoring from the exported JSON (mirrors scikit-learn)
# ---------------------------------------------------------------------------

TOKEN_RE = re.compile(r"(?u)\b\w\w+\b")


def strip_accents_unicode(s):
    nfkd = unicodedata.normalize("NFKD", s)
    return "".join(c for c in nfkd if not unicodedata.combining(c))


def score_from_json(text, m):
    doc = strip_accents_unicode(text.lower())
    tokens = TOKEN_RE.findall(doc)
    grams = list(tokens)
    if m["ngram_range"][1] >= 2:
        grams += [f"{a} {b}" for a, b in zip(tokens, tokens[1:])]
    counts = Counter(g for g in grams if g in m["vocab"])
    vec = {}
    for g, c in counts.items():
        tf = 1.0 + math.log(c) if m["sublinear_tf"] else float(c)
        vec[g] = tf * m["vocab"][g]["idf"]
    norm = math.sqrt(sum(v * v for v in vec.values())) or 1.0
    logits = list(m["intercept"])
    for g, v in vec.items():
        for k in range(3):
            logits[k] += (v / norm) * m["vocab"][g]["coef"][k]
    mx = max(logits)
    ex = [math.exp(z - mx) for z in logits]
    tot = sum(ex)
    return [e / tot for e in ex]


def update_readme(r):
    """Rewrite the block between the results markers in README.md from results.json."""
    path = ROOT / "README.md"
    start, end = "<!-- results:start -->", "<!-- results:end -->"
    text = path.read_text(encoding="utf-8")
    if start not in text or end not in text:
        print("README.md: results markers not found, block not updated")
        return
    pc = lambda x: f"{100 * x:.1f}%"
    v, l = r["vader"], r["tfidf_lr"]
    d, s = r["dataset"]["distribution"], r["split"]
    block = "\n".join([
        start,
        f"*Generated by `scripts/evaluate_and_export.py` on {r['generated_at'][:10]}. "
        f"Do not edit by hand; full figures in [`results.json`](results.json).*",
        "",
        f"Dataset: {r['dataset']['name']}, {r['dataset']['n_total']:,} sentences "
        f"({d['negative']:,} negative, {d['neutral']:,} neutral, {d['positive']:,} positive). "
        f"Stratified split, seed {s['random_state']}: {s['n_train']:,} train, {s['n_test']:,} test.",
        "",
        "| Model (test set) | Accuracy | Macro-F1 | Recall negative | Recall neutral | Recall positive |",
        "|---|---|---|---|---|---|",
        f"| Always predict *{r['majority_baseline']['class']}* | {pc(r['majority_baseline']['accuracy'])} | – | – | – | – |",
        f"| VADER | {pc(v['accuracy'])} | {v['f1_macro']:.3f} | "
        f"{pc(v['per_class']['negative']['recall'])} | {pc(v['per_class']['neutral']['recall'])} | {pc(v['per_class']['positive']['recall'])} |",
        f"| TF-IDF + logistic regression | {pc(l['accuracy'])} | {l['f1_macro']:.3f} | "
        f"{pc(l['per_class']['negative']['recall'])} | {pc(l['per_class']['neutral']['recall'])} | {pc(l['per_class']['positive']['recall'])} |",
        end,
    ])
    i, j = text.index(start), text.index(end) + len(end)
    path.write_text(text[:i] + block + text[j:], encoding="utf-8")


def main():
    texts, labels = fsm.load_phrasebank()
    dataset_sha = hashlib.sha256(
        "\n".join(f"{l}\t{t}" for t, l in zip(texts, labels)).encode("utf-8")
    ).hexdigest()

    X_train, X_test, y_train, y_test = train_test_split(
        texts, labels, test_size=fsm.TEST_SIZE,
        random_state=fsm.RANDOM_STATE, stratify=labels,
    )

    vader_pred = fsm.vader_predict(X_test)
    vader_m = fsm.evaluate(y_test, vader_pred, "VADER")

    pipe = fsm.build_lr_pipeline()
    pipe.fit(X_train, y_train)
    lr_pred = [int(p) for p in pipe.predict(X_test)]
    lr_m = fsm.evaluate(y_test, lr_pred, "TF-IDF + LR")

    dist_all = Counter(labels)
    dist_test = Counter(y_test)
    majority_class = max(dist_test, key=dist_test.get)

    # ---- model.json for the demo --------------------------------------
    tfidf = pipe.named_steps["tfidf"]
    lr = pipe.named_steps["lr"]
    if list(lr.classes_) != [0, 1, 2]:
        raise RuntimeError(f"Unexpected class order: {lr.classes_}")
    vocab = {
        term: {
            "idf": round(float(tfidf.idf_[j]), ROUND),
            "coef": [round(float(lr.coef_[k, j]), ROUND) for k in range(3)],
        }
        for term, j in tfidf.vocabulary_.items()
    }
    sia = SentimentIntensityAnalyzer()
    model = {
        "labels": fsm.LABEL_NAMES,
        "lowercase": True,
        "strip_accents": "unicode",
        "token_pattern": r"(?u)\b\w\w+\b",
        "ngram_range": list(tfidf.ngram_range),
        "sublinear_tf": bool(tfidf.sublinear_tf),
        "norm": tfidf.norm,
        "intercept": [round(float(b), ROUND) for b in lr.intercept_],
        "vocab": vocab,
        "vader": {
            "lexicon": {w: v for w, v in sia.lexicon.items()},
            "pos_threshold": fsm.VADER_POS_THRESHOLD,
            "neg_threshold": fsm.VADER_NEG_THRESHOLD,
        },
        "metrics": {
            "test_size": len(y_test),
            "vader": {"accuracy": round(float(vader_m["accuracy"]), 4),
                      "f1_macro": round(float(vader_m["f1_macro"]), 4)},
            "lr": {"accuracy": round(float(lr_m["accuracy"]), 4),
                   "f1_macro": round(float(lr_m["f1_macro"]), 4)},
        },
        "provenance": {
            "dataset": fsm.DATASET_NAME,
            "dataset_sha256": dataset_sha,
            "weights_license": "Weights are derived from Financial PhraseBank "
                               "(Malo et al., 2014), CC BY-NC-SA 3.0.",
            "vader_license": "VADER lexicon (Hutto & Gilbert, 2014), MIT.",
        },
    }

    # ---- self-check: JSON scoring must reproduce scikit-learn ----------
    sk_proba = pipe.predict_proba(X_test)
    mismatches, max_diff = 0, 0.0
    for text, p_sk in zip(X_test, sk_proba):
        p_js = score_from_json(text, model)
        max_diff = max(max_diff, max(abs(a - b) for a, b in zip(p_js, p_sk)))
        if int(np.argmax(p_js)) != int(np.argmax(p_sk)):
            mismatches += 1
    if mismatches:
        raise RuntimeError(f"Export check failed: {mismatches} label mismatches")

    probes = []
    for s in PROBE_SENTENCES:
        comp = sia.polarity_scores(s)["compound"]
        p = pipe.predict_proba([s])[0]
        probes.append({
            "sentence": s,
            "vader_compound": comp,
            "vader_label": ("positive" if comp >= fsm.VADER_POS_THRESHOLD else
                            "negative" if comp <= fsm.VADER_NEG_THRESHOLD else "neutral"),
            "lr_label": fsm.LABEL_NAMES[int(np.argmax(p))],
            "lr_proba": {n: round(float(x), 4) for n, x in zip(fsm.LABEL_NAMES, p)},
        })

    results = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "environment": {"python": platform.python_version(),
                        "scikit_learn": sklearn.__version__,
                        "nltk": nltk.__version__},
        "dataset": {
            "name": fsm.DATASET_NAME,
            "source_url": fsm.HF_PARQUET_URL if fsm.USE_HUGGINGFACE else None,
            "sha256": dataset_sha,
            "n_total": len(texts),
            "distribution": {n: dist_all[k] for k, n in enumerate(fsm.LABEL_NAMES)},
        },
        "split": {
            "method": "stratified random split",
            "test_size": fsm.TEST_SIZE,
            "random_state": fsm.RANDOM_STATE,
            "n_train": len(X_train),
            "n_test": len(X_test),
            "test_distribution": {n: dist_test[k] for k, n in enumerate(fsm.LABEL_NAMES)},
        },
        "majority_baseline": {
            "class": fsm.LABEL_NAMES[majority_class],
            "accuracy": dist_test[majority_class] / len(y_test),
        },
        "vader": summarize(vader_m, y_test, vader_pred),
        "tfidf_lr": summarize(lr_m, y_test, lr_pred),
        "export_check": {"label_mismatches": mismatches,
                         "max_probability_diff": max_diff},
        "probes": probes,
    }

    (ROOT / "results.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    update_readme(results)
    out = ROOT / "docs" / "demo" / "model.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(model, separators=(",", ":")), encoding="utf-8")

    print(f"Dataset   : {fsm.DATASET_NAME}, n={len(texts)}")
    print(f"Test set  : n={len(y_test)}, majority '{fsm.LABEL_NAMES[majority_class]}' "
          f"= {results['majority_baseline']['accuracy']:.3f}")
    print(f"VADER     : acc {vader_m['accuracy']:.3f} | macro-F1 {vader_m['f1_macro']:.3f}")
    print(f"TF-IDF+LR : acc {lr_m['accuracy']:.3f} | macro-F1 {lr_m['f1_macro']:.3f}")
    print(f"Export    : OK, max prob. diff {max_diff:.2e}, "
          f"model.json {out.stat().st_size / 1024:.0f} KB")


if __name__ == "__main__":
    main()
